<p>Formål: bot-beskyttelse via kontrol af et mindsteinterval mellem åbning af formularen og indsendelse.</p>
<p>Retsgrundlag: §&nbsp;25, stk.&nbsp;2, nr.&nbsp;2, i den tyske TDDDG (strengt nødvendig for at levere den tjeneste, brugeren udtrykkeligt har anmodet om, nemlig indsendelse af formularen). Der kræves intet samtykke hertil, og der anvendes derfor intet samtykkebanner.</p>
<p>Opbevaringsperiode: sessionens varighed, senest når browseren lukkes.</p>

